def tier(pts, fill=TERRA, band=LEAF, shrink=0.86):
    cx = sum(p[0] for p in pts) / len(pts)
    cy = sum(p[1] for p in pts) / len(pts)
    inner = [(round(cx + (x - cx) * shrink, 1), round(cy + (y - cy) * shrink + (1 - shrink) * 18, 1)) for x, y in pts]
    return PG(pts, band, 14) + PG(inner, fill, 0) + PG(inner, 'none', 5)


